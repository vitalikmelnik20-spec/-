function polyLength(p, closed) {
  let L = 0; for (let i = 1; i < p.length; i++) L += Math.hypot(p[i][0] - p[i - 1][0], p[i][1] - p[i - 1][1]);
  if (closed) L += Math.hypot(p[0][0] - p[p.length - 1][0], p[0][1] - p[p.length - 1][1]);
  return L;
}
/* the first fraction f of a polyline (for draw-on animations) */
function partialPoly(p, f, closed = false) {
  const pts = closed ? p.concat([p[0]]) : p;
  const total = polyLength(pts, false) * clamp(f);
  const out = [pts[0]]; let acc = 0;
  for (let i = 1; i < pts.length; i++) {
    const seg = Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
    if (acc + seg >= total) { const t = (total - acc) / (seg || 1); out.push(mix2(pts[i - 1], pts[i], t)); break; }
    out.push(pts[i]); acc += seg;
  }
  return out;
}
