"""Ukraine outline (incl. Crimea) -> SVG path for the opening map (remotion-lab/src/zahid/uaMap.ts).
Source: johan/world.geo.json countries/UKR.geo.json (public domain). Equirectangular, cos(49 deg) x-scale."""
import json, math
r = json.load(open("assets/UKR.geo.json"))["features"][0]["geometry"]["coordinates"][0]
k = math.cos(math.radians(49)); lon0, lon1, lat0, lat1 = 22.0, 40.3, 44.3, 52.45
W = 960; S = W / ((lon1 - lon0) * k); H = round((lat1 - lat0) * S)
P = lambda lon, lat: (round((lon - lon0) * k * S, 1), round((lat1 - lat) * S, 1))
path = "M" + " L".join(f"{x} {y}" for x, y in (P(*p) for p in r)) + " Z"
cities = {"lviv": (24.0316, 49.8429), "uzh": (22.2879, 48.6208), "frank": (24.7111, 48.9226), "kyiv": (30.5234, 50.4501)}
open("../remotion-lab/src/zahid/uaMap.ts", "w").write(
    "// generated by zahid/src/make_map.py - Ukraine outline incl. Crimea (public-domain world.geo.json)\n"
    f"export const UA_W = {W};\nexport const UA_H = {H};\nexport const UA_PATH = {json.dumps(path)};\n"
    + "".join(f"export const {n.upper()} = {{ x: {P(*c)[0]}, y: {P(*c)[1]} }};\n" for n, c in cities.items()))
print(W, H, {n: P(*c) for n, c in cities.items()})
